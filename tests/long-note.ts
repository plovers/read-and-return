/** A multi-megabyte Markdown note, also exportable for manual host testing. */
export function longNote(sections = 3000): string {
  const blocks = ['# 长笔记导航验收样本\n\n请在不同章节设置返回点，检查插入、删除、模式切换后的恢复。'];
  for (let i = 1; i <= sections; i++) blocks.push([
    `## 第 ${i} 节：阅读札记`, '',
    `本节记录第 ${i} 次阅读。长篇资料中的位置应该跟随文本上下文，而不只是屏幕像素。`, '',
    '阅读时先查看当前章节，再跳到笔记顶部对照提纲，最后返回继续阅读。',
    `唯一定位段落 ${i}：此处包含中文、English、符号 → 和 **强调文字**，用于确认返回位置。`, '',
    '- 第一项：保留正文，不添加导航标记。', '- 第二项：选择文字时不应误触悬浮按钮。', '',
    '> 引用块：字体大小和屏幕宽度改变之后，文本的行高可能发生变化。', '',
    '| 操作 | 预期 |', '| --- | --- |', '| 顶部 | 保存当前可见位置 |', '| 返回 | 回到原来的上下文 |', '',
    '```markdown', '# 代码块中的标题不应作为章节锚点', `example-${i}`, '```', '',
    '### 小结', '', '这是多次出现的相同段落，用于检验重复文本定位。', '',
    `第 ${i} 节结束；继续阅读下一节。`, ''
  ].join('\n'));
  return blocks.join('\n');
}
